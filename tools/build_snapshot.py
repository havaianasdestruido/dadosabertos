#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Render the TSV captures in ``tests/fixtures/real`` into an on-disk replica of
the six listings, using each site's own index dialect.

    python3 tools/build_snapshot.py --out /tmp/snapshots

The result is a directory tree that can be served by ``tests/replica_server.py``
and crawled with ``--rewrite`` so that the crawler sees the real URLs while the
bytes come from the local disk. ``tools/snapshot_inventory.py`` wires that up.

Captures are faithful in *content* (names, dates, sizes exactly as published);
the markup is regenerated, so this is a behavioural snapshot, not a byte copy.
"""

